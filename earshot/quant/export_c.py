"""Emit a QModel as csrc-compatible C source (earshot_model.c)."""

from pathlib import Path

import numpy as np

from earshot.quant.quantize import QModel

_OPS = {"conv": "ES_CONV", "dwconv": "ES_DWCONV", "avgpool": "ES_AVGPOOL", "fc": "ES_FC"}


def c_weight_layout(op: str, w: np.ndarray) -> np.ndarray:
    """Reorder weights into the layout earshot.c indexes."""
    if op == "fc":
        return w.T  # (in, out) -> (out, in)
    return w  # conv (kh, kw, cin, cout), dwconv (kh, kw, c): already what earshot.c wants


def _array(ctype: str, name: str, values: np.ndarray, per_line: int = 24) -> str:
    vals = np.asarray(values).ravel()
    if ctype == "float":
        items = [f"{float(np.float32(v))!r}f" for v in vals]
    else:
        items = [str(int(v)) for v in vals]
    lines = [", ".join(items[i : i + per_line]) for i in range(0, len(items), per_line)]
    return f"static const {ctype} {name}[{len(vals)}] = {{\n    " + ",\n    ".join(lines) + "\n};\n"


def _float(x) -> str:
    return f"{float(np.float32(x))!r}f"


def model_c_source(qm: QModel, source: str = "") -> str:
    out = [
        "/* GENERATED by earshot/quant/export_c.py - do not edit. */",
        f"/* source: {source} */" if source else "",
        '#include "earshot.h"',
        "",
    ]
    max_act = max(int(np.prod(L.out_shape)) for L in qm.layers)
    max_ch = max(max(L.in_shape[-1], L.out_shape[-1]) for L in qm.layers)
    t, f = qm.layers[0].in_shape[:2]
    out += [
        f"_Static_assert({max_act} <= ES_MAX_ACTIVATION, \"raise ES_MAX_ACTIVATION\");",
        f"_Static_assert({max_ch} <= ES_MAX_CHANNELS, \"raise ES_MAX_CHANNELS\");",
        f"_Static_assert({t * f} <= ES_MAX_INPUT, \"raise ES_MAX_INPUT\");",
        "",
        _array("float", "norm_mean", qm.norm_mean),
        _array("float", "norm_std", qm.norm_std),
    ]

    table = []
    for i, L in enumerate(qm.layers):
        if L.w is not None:
            out.append(_array("int8_t", f"w{i}", c_weight_layout(L.op, L.w)))
            out.append(_array("int32_t", f"b{i}", L.b))
        out.append(_array("int32_t", f"mult{i}", L.mult))
        out.append(_array("int32_t", f"shift{i}", L.shift))
        in_hw = L.in_shape[:2] if len(L.in_shape) == 3 else (1, 1)
        out_hw = L.out_shape[:2] if len(L.out_shape) == 3 else (1, 1)
        k = L.w.shape[:2] if L.op in ("conv", "dwconv") else (1, 1)
        table.append(
            f"    {{ /* {i}: {L.name} */\n"
            f"        .op = {_OPS[L.op]},\n"
            f"        .in_h = {in_hw[0]}, .in_w = {in_hw[1]}, .in_c = {L.in_shape[-1]},\n"
            f"        .out_h = {out_hw[0]}, .out_w = {out_hw[1]}, .out_c = {L.out_shape[-1]},\n"
            f"        .k_h = {k[0]}, .k_w = {k[1]}, .stride_h = {L.stride[0]}, .stride_w = {L.stride[1]},\n"
            f"        .pad_top = {L.pad[0]}, .pad_left = {L.pad[1]},\n"
            f"        .in_zp = {L.in_zp}, .out_zp = {L.out_zp}, .act_min = {L.act_min},\n"
            f"        .weights = {f'w{i}' if L.w is not None else 'NULL'}, .bias = {f'b{i}' if L.b is not None else 'NULL'},\n"
            f"        .mult = mult{i}, .shift = shift{i},\n"
            f"    }},"
        )
    out.append("static const es_layer layers[] = {\n" + "\n".join(table) + "\n};\n")
    names = ", ".join(f'"{c}"' for c in qm.classes)
    out.append(f"static const char *const class_names[] = {{{names}}};\n")
    out.append(
        "const es_model earshot_model = {\n"
        f"    .num_layers = {len(qm.layers)}, .layers = layers,\n"
        f"    .in_frames = {t}, .in_mels = {f}, .num_classes = {len(qm.classes)},\n"
        "    .class_names = class_names,\n"
        "    .norm_mean = norm_mean, .norm_std = norm_std,\n"
        f"    .input_scale = {_float(qm.input_scale)}, .input_zp = {qm.input_zp},\n"
        f"    .output_scale = {_float(qm.output_scale)}, .output_zp = {qm.output_zp},\n"
        "};\n"
    )
    return "\n".join(out)


def write_model_c(qm: QModel, path: Path, source: str = "") -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(model_c_source(qm, source))
    return path
